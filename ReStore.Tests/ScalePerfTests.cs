using System.Diagnostics;
using FluentAssertions;
using Moq;
using ReStore.Core.src.backup;
using ReStore.Core.src.core;
using ReStore.Core.src.monitoring;
using ReStore.Core.src.storage.local;
using ReStore.Core.src.utils;
using Xunit.Abstractions;

namespace ReStore.Tests;

/// <summary>
/// Scale gates (Category=Perf, run by the nightly workflow, excluded from the normal run). Budgets are deliberately generous:
/// they catch "everything is buffered in memory" or "something went quadratic", not small slowdowns.
/// </summary>
[Trait("Category", "Perf")]
[Collection("Perf")] // one at a time: process-wide allocation and timing numbers must not include a sibling test
public class ScalePerfTests(ITestOutputHelper output) : IDisposable
{
    private readonly string _root = Path.Combine(TestEnvironment.RootDirectory, "scaleperf_" + Guid.NewGuid().ToString("N"));
    private readonly TestLogger _logger = new();

    public void Dispose()
    {
        try { Directory.Delete(_root, true); } catch { }
    }

    /// <summary>Deterministic pseudo-random bytes of a fixed length, generated on read (nothing is stored).</summary>
    private sealed class GeneratedStream(long length) : Stream
    {
        private long _position;
        private uint _state = 2463534242;

        public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));

        public override int Read(Span<byte> buffer)
        {
            var n = (int)Math.Min(buffer.Length, length - _position);
            for (var i = 0; i < n; i++)
            {
                _state ^= _state << 13;
                _state ^= _state >> 17;
                _state ^= _state << 5;
                buffer[i] = (byte)_state;
            }

            _position += n;
            return n;
        }

        public override bool CanRead => true;
        public override bool CanSeek => false;
        public override bool CanWrite => false;
        public override long Length => length;
        public override long Position { get => _position; set => throw new NotSupportedException(); }
        public override void Flush() { }
        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
    }

    [PerfFact]
    public async Task OneGigabyteFile_IsStreamed_WithBoundedMemoryAndTime()
    {
        const long size = 1L << 30;
        // A real sparse file (the chunker checks it exists) whose content is replaced by generated bytes when opened.
        Directory.CreateDirectory(_root);
        var hugePath = Path.Combine(_root, "huge.bin");
        using (var sparse = new FileStream(hugePath, FileMode.Create))
        {
            sparse.SetLength(size);
        }

        var service = new ChunkingService(_logger, new ChunkDiffingConfig(), new EncryptionService(_logger), false, null,
            _ => new GeneratedStream(size), algorithmVersion: 3);
        long maxHeap = 0;
        var chunks = 0;
        Task Sink(ChunkBuildPayload _, CancellationToken __)
        {
            // Sampling the live managed heap every 64 chunks: a buffered file would show up as ~1 GB here.
            if ((++chunks & 63) == 0)
            {
                maxHeap = Math.Max(maxHeap, GC.GetTotalMemory(forceFullCollection: true));
            }

            return Task.CompletedTask;
        }

        var sw = Stopwatch.StartNew();
        var result = await service.BuildFileManifestEntryAsync(hugePath, _root, Sink);
        sw.Stop();

        output.WriteLine($"PERF 1 GB stream: {sw.Elapsed.TotalSeconds:F1} s ({1024 / sw.Elapsed.TotalSeconds:F0} MB/s), {result.FileEntry.Chunks.Count} chunks, max managed heap {maxHeap / (1024 * 1024)} MB, peak working set {Process.GetCurrentProcess().PeakWorkingSet64 / (1024 * 1024)} MB");

        result.FileEntry.Chunks.Count.Should().BeGreaterThan(1000);
        maxHeap.Should().BeLessThan(256L * 1024 * 1024, "a 1 GB file must be streamed, not buffered");
        sw.Elapsed.Should().BeLessThan(TimeSpan.FromMinutes(5));
    }

    [PerfFact]
    public async Task FiftyThousandSmallFiles_BackUpAndRebackUp_WithinBudget()
    {
        const int files = 50_000;
        var source = Path.Combine(_root, "src");
        var storageDir = Path.Combine(_root, "storage");
        Directory.CreateDirectory(storageDir);
        var random = new Random(20260101);
        var content = new byte[4096];
        for (var i = 0; i < files; i++)
        {
            var folder = Path.Combine(source, "d" + (i % 200));
            if (i < 200)
            {
                Directory.CreateDirectory(folder);
            }

            random.NextBytes(content);
            File.WriteAllBytes(Path.Combine(folder, $"f{i}.bin"), content.AsSpan(0, 1024 + random.Next(3072)).ToArray());
        }

        var state = new SystemState(_logger);
        state.SetStateFilePath(Path.Combine(_root, "state.json"));
        var config = new Mock<IConfigManager>();
        config.Setup(c => c.Retention).Returns(new RetentionConfig { Enabled = false, KeepLastPerDirectory = 10, MaxAgeDays = 30 });
        config.Setup(c => c.GlobalStorageType).Returns("local");
        config.Setup(c => c.SizeThresholdMB).Returns(100);
        config.Setup(c => c.Encryption).Returns(new EncryptionConfig { Enabled = false });
        config.Setup(c => c.ExcludedPatterns).Returns([]);
        config.Setup(c => c.ExcludedPaths).Returns([]);
        config.Setup(c => c.BackupType).Returns(BackupType.Incremental);
        config.Setup(c => c.WatchDirectories).Returns([]);
        config.Setup(c => c.MaxFileSizeMB).Returns(100);
        config.SetupGet(c => c.ChunkDiffing).Returns(new ChunkDiffingConfig());
        config.Setup(c => c.CreateStorageAsync(It.IsAny<string>())).Returns(async () =>
        {
            var storage = new LocalStorage(_logger);
            await storage.InitializeAsync(new Dictionary<string, string> { { "path", storageDir } });
            return storage;
        });
        var coordinator = new RepositoryCoordinator(Path.Combine(_root, "repository.lock"));
        Backup NewBackup() => new(_logger, state, new SizeAnalyzer(), config.Object, null, coordinator);

        var first = Stopwatch.StartNew();
        var firstResult = await NewBackup().BackupDirectoryAsync(source);
        first.Stop();
        var second = Stopwatch.StartNew();
        var secondResult = await NewBackup().BackupDirectoryAsync(source);
        second.Stop();

        var stateBytes = new FileInfo(Path.Combine(_root, "state.json")).Length;
        var peak = Process.GetCurrentProcess().PeakWorkingSet64;
        output.WriteLine($"PERF {files} files: first backup {first.Elapsed.TotalSeconds:F1} s, no-change backup {second.Elapsed.TotalSeconds:F1} s, state.json {stateBytes / 1024} KB, peak working set {peak / (1024 * 1024)} MB");

        firstResult.Skipped.Should().BeEmpty();
        secondResult.Skipped.Should().BeEmpty();
        first.Elapsed.Should().BeLessThan(TimeSpan.FromMinutes(10));
        second.Elapsed.Should().BeLessThan(first.Elapsed, "an unchanged re-run must be cheaper than the first full backup");
        stateBytes.Should().BeLessThan(200L * 1024 * 1024, "state growth per file must stay small");
        peak.Should().BeLessThan(3L * 1024 * 1024 * 1024, "50k small files must not need gigabytes of memory");
    }
}
